// Gera QA_REPORT_PONTO_CEGO.md a partir de /tmp/weapons_qa.json (test/weapons_qa.js) e do código-fonte.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const J = JSON.parse(fs.readFileSync('/tmp/weapons_qa.json', 'utf8'));
const wm = fs.readFileSync(path.join(ROOT, 'src/render/12e-wmodel.js'), 'utf8');
const model = {};
for (const m of wm.matchAll(/^\s+([a-z0-9_]+):\s*\{m:'([a-z0-9]+)'/gm)) model[m[1]] = 'wm_' + m[2] + '.bin';
const pct = (x) => Math.round(x * 100) + '%';
const out = [];
const P = (s = '') => out.push(s);
const ws = J.weapons;
const okAll = (w) => !w.fatal && Object.values(w.checks).every((c) => c.ok);
const passN = ws.filter(okAll).length;

P('# QA — Ponto Cego: testes funcionais de armas');
P();
P(`Gerado em ${J.when.slice(0, 19).replace('T', ' ')} (UTC). Script: \`test/weapons_qa.js\`. Relatório: \`tools/qa_report.mjs\`.`);
P();
P('## Resumo');
P();
P(`${ws.length} armas testadas, ${passN} passaram em todos os testes, ${ws.length - passN} falharam. Erros reais no console do navegador: ${J.errs.filter((e) => !/GPU stall|ReadPixels/.test(e.m)).length}.`);
P();
P('Como o teste roda: abre o jogo no Chromium (Playwright), inicia uma partida, avança a simulação até a fase de ação e, para cada arma, executa o roteiro abaixo no estado real do jogo (mesmo código da partida, passo fixo de 60 Hz). O jogador fica invulnerável e a rodada é mantida aberta para o relógio não virar de rodada no meio do teste. O jogo não tem um cenário de treino separado: o teste usa a partida normal, com um bot parado na frente para medir dano.');
P();
P('Roteiro por arma:');
P();
P('1. Equipar a arma e conferir os dados de configuração.');
P('2. Atirar sem parar até esvaziar o pente (arma automática segura o gatilho, semiautomática aperta um clique por tiro). Conferir que o pente zera, que nunca fica negativo e que a reserva não muda.');
P('3. Medir a cadência (tempo entre tiros) e comparar com a configurada.');
P('4. Com o pente vazio e sem reserva, apertar o gatilho: não pode sair tiro.');
P('5. Recarregar: medir o tempo, conferir que o tiro fica bloqueado durante a recarga, que o pente enche e que a reserva desconta.');
P('6. Recarga parcial (só repõe o que faltou) e recarga sem reserva (R não faz nada).');
P('7. ADS: botão direito entra na mira no tempo configurado, o campo de visão (FOV) muda e a mira sai ao soltar. Mirar durante a recarga não deve entrar em ADS.');
P('8. Dano: tiros num bot a 6 metros; o HP do bot precisa cair.');
P('9. HUD: o texto de munição do HUD precisa bater com o estado da arma.');
P('10. Cobertura da tela: compara o quadro com e sem as mãos/arma para medir quanto da tela o modelo ocupa (quadril, mira e pior momento da recarga).');
P('11. Monitorar console, erros de página e requisições que falham durante tudo.');
P();
P('## Dados das armas (análise estática do código)');
P();
P('Fonte: `src/sim/01-data.js` (WEAPONS) e `src/render/12e-wmodel.js` (modelo 3D).');
P();
P('| Arma | Nome | Tipo | Slot | Dano | Cadência (s) | Tiros/min | Pente / reserva | Recarga (s) | Modelo 3D |');
P('|---|---|---|---|---|---|---|---|---|---|');
for (const w of ws) P(`| ${w.id} | ${w.name} | ${w.type}${w.auto ? ', auto' : ''} | ${w.slot === 'p' ? 'principal' : 'secundária'} | ${w.dmg}${w.pellets > 1 ? ' × ' + w.pellets : ''} | ${w.rate} | ${Math.round(60 / w.rate)} | ${w.mag} / ${w.res} | ${w.reload} | ${model[w.id] || 'modelo simples'} |`);
P();
P('## Status por arma');
P();
P('| Arma | Status | Testes que falharam |');
P('|---|---|---|');
for (const w of ws) {
  const f = Object.entries(w.checks).filter(([, c]) => !c.ok).map(([k, c]) => `${k} (${c.info})`);
  P(`| ${w.name} (${w.id}) | ${okAll(w) ? 'Passou' : 'Falhou'} | ${w.fatal ? 'ERRO FATAL: ' + w.fatal.split('\n')[0] : f.join('; ') || '-'} |`);
}
P();
P('## Medidas');
P();
P('| Arma | Cadência medida / config (s) | Recarga medida (s) / config | ADS (s) / config | FOV quadril → mira | Dano visto | Tela ocupada: quadril / mira / recarga (pico) | Render (ms)* |');
P('|---|---|---|---|---|---|---|---|');
const num = (s, re) => { const m = (s || '').match(re); return m ? m[1] : '?'; };
for (const w of ws) {
  const C = w.checks;
  const recMed = num(C['tempo de recarga']?.info, /medido ([\d.]+)s/);
  const adsMed = num(C['ADS entra']?.info, /em ([\d.]+)s/);
  const fov = (C['ADS muda a câmera (FOV)']?.info || '').split(' · ')[0].replace('FOV ', '');
  P(`| ${w.name} | ${w.cadMeasured} / ${w.rate} | ${recMed} / ${w.reload} | ${adsMed} / ${w.adsT} | ${fov} | ${w.dmgSeen} | ${pct(w.covHip)} / ${pct(w.covAds)} / ${pct(w.covReload)} | ${w.renderMs} |`);
}
P();
P('Dano visto: maior dano em tiro no corpo do bot de teste. Fica abaixo do dano base porque o bot usa blindagem (o dano cai pela redução da blindagem). Tiro na cabeça mata na hora com qualquer arma (regra do jogo); balins de escopeta não têm essa regra. Tela ocupada: medida por diferença de pixels, e tende a subir na recarga quando a manga ou a arma chega perto da câmera.');
P();
P('*Render medido com renderização por software (SwiftShader), sem GPU. Serve só para comparar uma arma com outra; no seu computador será bem mais rápido.');
P();
P('## Bugs lógicos e achados');
P();
const bugs = [];
for (const w of ws) for (const [k, c] of Object.entries(w.checks)) if (!c.ok) bugs.push({ sev: 'Alta', t: `${w.name}: falha em "${k}" — ${c.info}` });
const slow = ws.filter((w) => w.rate < 1 && w.cadMeasured > w.rate * 1.08 && w.cadMeasured > 0);
if (slow.length) bugs.push({ sev: 'Média', t: `Cadência real abaixo da configurada em ${slow.length} armas. O passo da simulação é de 1/60 s e o tempo entre tiros é arredondado para cima (o resto do intervalo se perde). Pior caso: ${slow.sort((a, b) => b.cadMeasured / b.rate - a.cadMeasured / a.rate).slice(0, 4).map((w) => `${w.name} ${w.cadMeasured}s em vez de ${w.rate}s (${Math.round((w.cadMeasured / w.rate - 1) * 100)}% mais lenta)`).join('; ')}. Correção sugerida: somar o intervalo ao resto (\`fireCD += rate\`) em vez de reiniciar. Muda o equilíbrio das armas rápidas, por isso não apliquei.` });
const big = ws.filter((w) => w.covReload > 0.25);
if (big.length) bugs.push({ sev: 'Média', t: `Na recarga o modelo (mão, manga e arma) ocupa mais de 25% da tela: ${big.map((w) => `${w.name} ${pct(w.covReload)}`).join(', ')}. Confirmado por imagem na SMG-11 (manga do braço esquerdo vira um tubo grande perto da câmera). Já era um item pendente de versões anteriores.` });
if (!bugs.length) P('Nenhum bug lógico encontrado.');
else bugs.forEach((b, i) => P(`${i + 1}. **${b.sev}.** ${b.t}`));
P();
P('Observação: este teste roda a simulação e mede o estado do jogo. Ele não substitui olhar a imagem: som, sensação de recuo e animação precisam de uma pessoa jogando. As fotos de cada arma (quadril e mira) ficam em `shots/qa_<arma>_hip.png` e `shots/qa_<arma>_ads.png`.');
P();
P('## Log de erros do console');
P();
const real = J.errs.filter((e) => !/GPU stall|ReadPixels/.test(e.m));
const env = J.errs.length - real.length;
if (!real.length) P('Nenhum erro de JavaScript, falha de carregamento de textura ou erro de física durante os testes.');
else { P('| Arma em teste | Tipo | Mensagem |'); P('|---|---|---|'); for (const e of real) P(`| ${e.w} | ${e.k} | ${e.m.replace(/\|/g, '/')} ${e.s || ''} |`); }
if (env) P(`\nAvisos do driver gráfico ignorados: ${env} (mensagem "GPU stall due to ReadPixels", vem da leitura de pixels do teste e do renderizador por software; não é do jogo).`);
fs.writeFileSync(path.join(ROOT, 'QA_REPORT_PONTO_CEGO.md'), out.join('\n') + '\n');
console.log('QA_REPORT_PONTO_CEGO.md escrito:', passN + '/' + ws.length, 'passaram');
